const actions = {
  FETCH_POPULATION_STATISTICS_REQUEST: "FETCH_POPULATION_STATISTICS_REQUEST",
  FETCH_POPULATION_STATISTICS_SUCCESS: "FETCH_POPULATION_STATISTICS_SUCCESS",
  FETCH_POPULATION_STATISTICS_FAILED: "FETCH_POPULATION_STATISTICS_FAILED",

  FETCH_COHORT_STATISTICS_REQUEST: "FETCH_COHORT_STATISTICS_REQUEST",
  FETCH_COHORT_STATISTICS_SUCCESS: "FETCH_COHORT_STATISTICS_SUCCESS",
  FETCH_COHORT_STATISTICS_FAILED: "FETCH_COHORT_STATISTICS_FAILED",

  fetchPopulationStatistics: () => ({
    type: actions.FETCH_POPULATION_STATISTICS_REQUEST,
  }),

  fetchCohortStatistics: (searchId, options = {}) => ({
    type: actions.FETCH_COHORT_STATISTICS_REQUEST,
    searchId,
    comparison: options.comparison === true,
    label: options.label,
  }),
};

export default actions;
